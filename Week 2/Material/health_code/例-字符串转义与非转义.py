import pandas as pd

# "\201"进行转义
str1 = "..\data\2016-2022年全国卫生技术人员统计表（万人）.xls"
print(str1)
#
# #在字符串前，加上“r”，字符串按原字符输出，"\201"未进行转义
str2 = r"..\data\2016-2022年全国卫生技术人员统计表（万人）.xls"
print(str2)

# 程序运行报错，文件无法读取，因为："\201"进行转义，改变了文件路径与文件名
df = pd.read_excel('..\data\2016-2022年全国卫生技术人员统计表（万人）.xls')
print(df)

# 文件正常读取，因为：字符串不进行转义
df = pd.read_excel(r'..\data\2016-2022年全国卫生技术人员统计表（万人）.xls')
print(df)

# 其他方法，读取文件，使用'/'，替代'\'，文件正常读取
df = pd.read_excel('../data/2016-2022年全国卫生技术人员统计表（万人）.xls')
print(df)